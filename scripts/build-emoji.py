#!/usr/bin/env python3
# Usage (from the repo root): npm pack emoji-datasource-twitter@16.0.0 && tar xzf emoji-datasource-twitter-16.0.0.tgz
#   python3 scripts/build-emoji.py package
# Builds the Twemoji sheet and the Lua emoji table used by Zuno.
import json, sys
from PIL import Image
CELL, PAD = 40, 1
STEP = CELL + 2 * PAD
SRC = sys.argv[1]  # unpacked emoji-datasource-twitter package folder
OUT_PNG, OUT_LUA = 'client/assets/emoji/twemoji-40.png', 'ui/zuno_ui/emoji_data.lua'
d = json.load(open(SRC + '/emoji.json'))
d = [e for e in d if e['has_img_twitter'] and e['category'] != 'Component']
d.sort(key=lambda e: e['sort_order'])
cats = ['Smileys & Emotion', 'People & Body', 'Animals & Nature', 'Food & Drink', 'Activities', 'Travel & Places', 'Objects', 'Symbols', 'Flags']
cols = 48
rows = (len(d) + cols - 1) // cols
sheet = Image.new('RGBA', (cols * STEP, rows * STEP), (0, 0, 0, 0))
def u(code): return ''.join(chr(int(c, 16)) for c in code.split('-'))
out = []
for i, e in enumerate(d):
    im = Image.open(SRC + '/img/twitter/64/' + e['image']).convert('RGBA').resize((CELL, CELL), Image.LANCZOS)
    sheet.paste(im, ((i % cols) * STEP + PAD, (i // cols) * STEP + PAD))
    names = e['short_names']
    alt = u(e['non_qualified']) if e.get('non_qualified') else None
    out.append((u(e['unified']), names, cats.index(e['category']) + 1, alt, e['name'].lower()))
# Twemoji is flat, so 256 colours look the same and the file is 5x smaller.
sheet.quantize(colors=256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE).save(OUT_PNG, optimize=True)
def q(s): return '"' + ''.join('\\%d' % b if b < 32 or b > 126 or chr(b) in '"\\' else chr(b) for b in s.encode('utf-8')) + '"'
L = ['-- Generated by scripts/build-emoji.py from emoji-datasource-twitter 16.0.0 (MIT).',
     '-- Images: Twemoji by Twitter / jdecked, CC-BY 4.0. One row per emoji: { text, short names, category, plain variant, name }',
     'return {', '  cell = %d, pad = %d, cols = %d, rows = %d, image = "assets/emoji/twemoji-40.png",' % (CELL, PAD, cols, rows),
     '  categories = { ' + ', '.join(q(c) for c in cats) + ' },', '  list = {']
for t, names, c, alt, name in out:
    L.append('    { %s, { %s }, %d, %s, %s },' % (q(t), ', '.join(q(n) for n in names), c, q(alt) if alt else 'nil', q(name)))
L += ['  },', '}', '']
open(OUT_LUA, 'w').write('\n'.join(L))
print(len(out), cols, rows)
